export const P2_CONTROLS_LINE =
  'P2: Arrows Move · Up Jump · Down Slide · ./R-Shift Dash · / Hook · \' Pull · M Dive · , Strike · ; Guard';

export function getControlBindings(handedness: Handedness, p2Enabled = false): ControlSchemeDisplay {
  if (handedness === 'left') {
    return {
      handedness: 'left',
      move: p2Enabled ? 'J / L' : 'Arrows / J·L',
      jump: p2Enabled ? 'I / Space' : 'Up / Space / I',
      slide: p2Enabled ? 'K' : 'Down / K',
      dash: p2Enabled ? 'N' : 'R-Shift / N',
      dive: 'B',
      attack: 'Click / U',
      grapple: 'R-Click / O',
      pull: 'H / V',
      defend: 'H',
      compactLine: p2Enabled
        ? 'P1 (Left-Hand): JL Move · I/Space Jump · K Slide · N Dash · O/R-Click Hook · U/Click Strike · B Dive | ' +
          P2_CONTROLS_LINE
        : 'Arrows/JL Move · Up/Space Jump · K/Down Slide · R-Shift/N Dash · O/R-Click Hook · ./; Pull · / or B Dive · U/Click Strike · H Parry',
    };
  }
  return {
    handedness: 'right',
    move: p2Enabled ? 'A / D' : 'A / D or Arrows',
    jump: 'W / Space',
    slide: 'S',
    dash: p2Enabled ? 'L-Shift / K' : 'Shift / K',
    dive: 'C',
    attack: 'Click / J',
    grapple: 'R-Click / E',
    pull: 'Q or V',
    defend: 'F / L',
    compactLine: p2Enabled
      ? 'P1: AD Move · W/Space Jump · S Slide · L-Shift/K Dash · E/R-Click Hook · Q Pull · C Dive · J/Click Strike · F Guard | ' +
        P2_CONTROLS_LINE
      : 'AD Move · W/Space Jump · S Slide · Shift/K Dash · E/R-Click Hook · Q Pull · C Dive · J/Click Strike · F/L Parry',
  };
}

